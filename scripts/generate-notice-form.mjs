#!/usr/bin/env node
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadNoticeTypes } from './lib/notice-content.mjs'

const outputPath = fileURLToPath(
  new URL('../.github/ISSUE_TEMPLATE/publish-notice.yml', import.meta.url)
)
const check = process.argv.includes('--check')
const noticeTypes = await loadNoticeTypes()
const options = noticeTypes
  .map(
    ({ value, label }) => `        - ${JSON.stringify(`${label} (${value})`)}`
  )
  .join('\n')

const generated = `# Generated by scripts/generate-notice-form.mjs from src/data/notice-types.ts.
# Run pnpm notice-form:generate after changing notice types.
name: Publish a notice
description: Create a validated notice pull request (write access required)
title: "[Publish notice] "
body:
  - type: markdown
    attributes:
      value: |
        This form opens a pull request; it does not publish immediately. For a time-critical compliance challenge, use the documented manual path.
  - type: dropdown
    id: notice_type
    attributes:
      label: Notice type
      options:
${options}
    validations:
      required: true
  - type: input
    id: notice_title
    attributes:
      label: Notice title
      placeholder: Exact title of the notice
    validations:
      required: true
  - type: textarea
    id: body
    attributes:
      label: Body
      description: Markdown content for the notice. It is copied without trimming or reflowing.
    validations:
      required: true
  - type: input
    id: notice_date
    attributes:
      label: Notice date
      description: Optional UTC timestamp for a statutory notice period (YYYY-MM-DDTHH:MM:SSZ).
      placeholder: 2026-08-11T14:30:00Z
  - type: dropdown
    id: verbatim
    attributes:
      label: Verbatim publication
      description: Select Yes only when the body must be rendered exactly as submitted.
      options:
        - "No"
        - "Yes"
    validations:
      required: true
  - type: input
    id: supersedes
    attributes:
      label: Supersedes
      description: Optional filename of the notice being corrected, without .md.
      placeholder: 2026-08-01-example-resolution
`

if (check) {
  let existing = ''
  try {
    existing = await readFile(outputPath, 'utf8')
  } catch {}

  if (existing !== generated) {
    console.error(
      'The notice issue form is stale. Run: pnpm notice-form:generate'
    )
    process.exitCode = 1
  } else {
    console.log('The notice issue form matches src/data/notice-types.ts.')
  }
} else {
  await mkdir(path.dirname(outputPath), { recursive: true })
  await writeFile(outputPath, generated)
  console.log(`Generated ${outputPath}`)
}
