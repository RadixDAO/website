#!/usr/bin/env node
// Generates the three governance-document issue forms from src/data/govern.json
// so their dropdowns can never drift from the index. `--check` fails CI when
// they are stale, mirroring scripts/generate-notice-form.mjs.
//
// Three forms rather than one because GitHub issue forms cannot show fields
// conditionally: a combined form would ask a registrant for a version and a
// transaction id, which is exactly the confusion this tooling exists to remove.

import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadGovernData } from './lib/governance-documents.mjs'

const templateDir = fileURLToPath(
  new URL('../.github/ISSUE_TEMPLATE', import.meta.url)
)
const check = process.argv.includes('--check')
const data = await loadGovernData()

const quote = (value) => JSON.stringify(value)
const options = (values, indent = '        ') =>
  values.map((value) => `${indent}- ${quote(value)}`).join('\n')

const documentOptions = (predicate) => {
  const matching = data.documents.filter(predicate)
  // A form with no options is invalid YAML for GitHub, and an empty dropdown is
  // a confusing dead end. A single explanatory option is a clearer failure.
  if (matching.length === 0) return ['(no eligible documents)']
  return matching.map((doc) => `${doc.title} (${doc.id})`)
}

const header = `# Generated by scripts/generate-document-forms.mjs from src/data/govern.json.
# Run pnpm document-forms:generate after changing the document index.`

const publishFields = (verb) => `  - type: input
    id: version
    attributes:
      label: Version
      description: Semantic version of the ${verb} document, as recorded in registry.json.
      placeholder: "1.0.0"
    validations:
      required: true
  - type: input
    id: commit
    attributes:
      label: Source commit
      description: Full 40-character commit SHA in the governance repository holding this version.
      placeholder: 00eb84ca97b7fe78b23cb59fa72b3a4f409dc416
    validations:
      required: true
  - type: input
    id: effective
    attributes:
      label: Effective date
      description: The date this version takes effect (YYYY-MM-DD).
      placeholder: "2026-09-21"
    validations:
      required: true
  - type: input
    id: transaction
    attributes:
      label: Activating transaction
      description: Optional. The Radix transaction that recorded this document's digest on-chain.
      placeholder: txid_rdx1...
`

const forms = {
  'register-document.yml': `${header}
name: Register a governance document
description: Add a new document to the index as a pending draft (write access required)
title: "[Register document] "
body:
  - type: markdown
    attributes:
      value: |
        Use this when a new document exists in the governance repository and should appear on the site as a draft. It does not activate anything. This form opens a pull request; it does not publish immediately.
  - type: input
    id: document_title
    attributes:
      label: Document title
      placeholder: Records Retention Policy
    validations:
      required: true
  - type: input
    id: summary
    attributes:
      label: Summary
      description: One plain-language sentence. It is a pointer to the document, never a restatement of its rules.
    validations:
      required: true
  - type: input
    id: source_path
    attributes:
      label: Source path
      description: Path to the Markdown file within the governance repository.
      placeholder: pending/governance/records-retention-policy.md
    validations:
      required: true
  - type: dropdown
    id: group
    attributes:
      label: Group
      description: Which section of the Govern page this document belongs in.
      options:
${options(data.groups.map((group) => group.name))}
    validations:
      required: true
  - type: input
    id: document_id
    attributes:
      label: Document id
      description: Optional. Defaults to the source filename without .md.
      placeholder: records-retention-policy
`,

  'activate-document.yml': `${header}
name: Activate a governance document
description: Move a pending document into force after an activation vote (write access required)
title: "[Activate document] "
body:
  - type: markdown
    attributes:
      value: |
        Use this when an activation vote has passed for a document currently shown as pending. **Do not enter a digest.** The workflow downloads the published PDF, hashes it, and cross-checks the result against registry.json in the governance repository.
  - type: dropdown
    id: document
    attributes:
      label: Document
      options:
${options(documentOptions((doc) => doc.status === 'pending'))}
    validations:
      required: true
${publishFields('activated')}`,

  'publish-document-version.yml': `${header}
name: Publish a new document version
description: Replace the version in force after an amendment vote (write access required)
title: "[New document version] "
body:
  - type: markdown
    attributes:
      value: |
        Use this when an amendment vote has passed for a document already in force. The previous version stops being shown on the site; its digest is retained so anyone holding that PDF can still confirm it is genuine. **Do not enter a digest.**
  - type: dropdown
    id: document
    attributes:
      label: Document
      options:
${options(documentOptions((doc) => doc.status === 'in-force'))}
    validations:
      required: true
${publishFields('amended')}`
}

let stale = false

for (const [name, contents] of Object.entries(forms)) {
  const target = path.join(templateDir, name)

  if (check) {
    let existing = ''
    try {
      existing = await readFile(target, 'utf8')
    } catch {}
    if (existing !== contents) {
      console.error(`${name} is stale.`)
      stale = true
    }
    continue
  }

  await mkdir(templateDir, { recursive: true })
  await writeFile(target, contents)
  console.log(`Generated ${target}`)
}

if (check) {
  if (stale) {
    console.error('Run: pnpm document-forms:generate')
    process.exitCode = 1
  } else {
    console.log('The document issue forms match src/data/govern.json.')
  }
}
